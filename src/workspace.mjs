// Project Workspace artifacts. Pure string generation; the browser downloads them locally.
import { PROVENANCE, OWNER, RUNTIME, TIERS } from "./catalog.mjs";
import { toManifest } from "./engine.mjs";
import { starterMarkdown } from "./starter.mjs";
import { stageHandoff } from "./handoff.mjs";

const q = v => JSON.stringify(String(v ?? ""));

function levelFromTier(tier) {
  const t = TIERS[tier];
  return {
    spec_required: t.spec,
    plan_required: t.plan,
    adr_required: t.adr,
    review_required: t.review,
    e2e: t.e2e,
    rollback_plan: t.rollback
  };
}

export function engineeringProfileYaml(plan) {
  const { config, profiles, tier, task } = plan;
  const levels = levelFromTier(tier.id);
  const hasEvals = profiles.some(p => ["ai-application", "rag", "agent"].includes(p));
  const hasBackup = profiles.some(p => ["saas", "enterprise", "infrastructure"].includes(p));
  const lines = [
    "# ENGINEERING_PROFILE.yaml — generated by Workbench; owned and editable by this project.",
    "# Levels: required | recommended | optional | not_applicable",
    "ownership:",
    "  current_owner: " + q(OWNER.repository),
    "  historical_provenance: " + q(PROVENANCE.repository + "@" + PROVENANCE.commit),
    "  governance_reference: " + q("AI-Native-Work-Learning-OS (reference only)"),
    "  runtime: " + q(RUNTIME.name + " " + RUNTIME.version),
    "project:",
    "  name: " + q(config.name),
    "  tier: " + q(tier.id),
    "  task: " + q(task.id),
    "  mode: " + q(config.mode),
    "  profiles: [" + profiles.join(", ") + "]",
    "lifecycle:",
    ...Object.entries(levels).map(([k, v]) => "  " + k + ": " + v),
    "quality:",
    "  unit_tests: required",
    "  integration_tests: " + (profiles.includes("saas") ? "required" : "recommended"),
    "  e2e: " + levels.e2e,
    "  evals: " + (hasEvals ? "required" : "not_applicable"),
    "security:",
    "  secret_scan: required",
    "  review: " + levels.review_required,
    "  dependency_audit: " + (profiles.includes("web") || profiles.includes("backend") ? "required" : "recommended"),
    "operations:",
    "  observability: recommended",
    "  rollback_plan: " + levels.rollback_plan,
    "  backup: " + (hasBackup ? "required" : "optional"),
    "exceptions: []",
    ""
  ];
  return lines.join("\n");
}

export function adrTemplate(plan) {
  return [
    "# ADR-NNNN · <决策标题>",
    "",
    "> 状态：PROPOSED / NOT_RUN。由 Workbench 生成草案，未经过评审。",
    "> 项目：" + plan.config.name + " · 任务：" + plan.task.id,
    "",
    "## 背景",
    "",
    "<迫使做出决定的力量：规模、成本、团队、现有组件、约束。>",
    "",
    "## 选项",
    "",
    "1. <选项 A> — <一行后果>",
    "2. <选项 B> — <一行后果>",
    "",
    "只有一个选项的决定通常是伪装成选择的约束。",
    "",
    "## 决策",
    "",
    "<一句话说明采用什么，以及为什么。>",
    "",
    "## 失效条件",
    "",
    "<什么事实出现时应重新审视该决策。>",
    "",
    "## 后果",
    "",
    "- 正向：",
    "- 负向：",
    "- 中性 / 新增义务：",
    "",
    "## 验证方式",
    "",
    "<如何知道架构按预期工作；不可验证说明尚未决定。>",
    ""
  ].join("\n");
}

export function verificationPlan(plan) {
  const lines = [
    "# " + plan.config.name + " · 验证计划（草案）", "",
    "> 状态：NOT_RUN。本文件只定义需要什么证据，不代表已执行。", "",
    "| 阶段 | 本任务重点 | 必需证据 | 状态 |", "|---|---|---|---|"
  ];
  for (const s of plan.stages)
    lines.push("| " + s.name + " | " + s.focus + " | " + s.evidence.join(", ") + " | NOT_RUN |");
  lines.push("",
    "## 证据分层", "",
    "- 代码检查：测试、静态检查、契约测试。",
    "- 真实环境：集成探针、真机、预发部署回执。",
    "- 消费者验收：真实用户按 AC 签收。",
    "",
    "三层不可互相替代。任何无法运行的检查标 UNKNOWN。", "");
  return lines.join("\n");
}

export function releaseChecklist(plan) {
  const lines = [
    "# " + plan.config.name + " · 发布检查单（草案）", "",
    "> 状态：NOT_RUN。发布需要明确授权与真实回执。", "",
    "- [ ] 验证证据齐备且没有未解释的 UNKNOWN",
    "- [ ] 数据库迁移与降级路径已在副本上验证",
    "- [ ] 备份已验证，恢复步骤可执行",
    "- [ ] 回滚方案已记录并演练过一次",
    "- [ ] 发布授权人已确认范围与时间窗口",
    "- [ ] 版本号与 CHANGELOG 已更新",
    "- [ ] 部署或商店发布回执已保存",
    "- [ ] 发布后监控与告警已观察",
    ""
  ];
  return lines.join("\n");
}

export function workspaceBundle(plan) {
  const slug = plan.slug;
  return {
    [slug + "-manifest.json"]: JSON.stringify(plan.manifest ?? toManifest(plan), null, 2) + "\n",
    [slug + "-ENGINEERING_PROFILE.yaml"]: engineeringProfileYaml(plan),
    [slug + "-spec-and-tickets-draft.md"]: starterMarkdown(plan),
    [slug + "-adr-draft.md"]: adrTemplate(plan),
    [slug + "-verification-plan.md"]: verificationPlan(plan),
    [slug + "-release-checklist.md"]: releaseChecklist(plan),
    [slug + "-agent-handoff.md"]: stageHandoff(plan, plan.stages[0].id)
  };
}
